import {byId} from './cards.js';
import {legalMoves,play,pass,outcome,opponent,seededRng,type Game,type Player,type Command} from './engine.js';

export type BotDifficulty='easy'|'normal'|'hard';
export type BotAction=Exclude<Command,{type:'mulligan'}>;
/** Deliberately contains no opposing hand IDs, deck IDs, replay or draw events. */
export interface BotView {
  player:Player;board:Game['board'];hand:number[];enemyHandCount:number;
  deckCounts:[number,number];discard:Game['discard'];passes:number;nextInstanceId:number;
  rulesVersion?:Game['rulesVersion'];
}
export interface BotOptions {difficulty?:BotDifficulty;seed?:number;maxNodes?:number;explain?:boolean;}
export interface BotCandidate {action:BotAction;score:number;immediate:number;replies:number;reason:string;}
export interface BotDecision {
  action:BotAction;difficulty:BotDifficulty;seed:number;
  stats:{nodes:number;maxNodes:number;rejected:number;depth:number;budgetReached:boolean};
  reason:string;candidates?:BotCandidate[];warning?:string;
}
export const DEFAULT_BOT_NODES={easy:64,normal:256,hard:256} as const;
// Public, fixed response hypotheses, NOT reconstructed opposing cards. No deck
// seed is used to infer hidden information. These cover basics, damage, replace.
export const RESPONSE_POOL=Object.freeze([1,7,8,13,20,26,39,51]);
export function observeGame(game:Game,player:Player=game.turn):BotView {
  if((player!==0&&player!==1)||game.phase!=='playing'||game.turn!==player)throw Error('Bot requires the current player in playing phase');
  return {player,board:structuredClone(game.board),hand:[...game.hands[player]],enemyHandCount:game.hands[opponent(player)].length,
    ...(game.rulesVersion?{rulesVersion:game.rulesVersion}:{}),
    deckCounts:[game.decks[0].length,game.decks[1].length],discard:structuredClone(game.discard),passes:game.passes,nextInstanceId:game.nextInstanceId};
}
/** Placeholder draws preserve hand counts. Reply hypotheses use the public pool
 * for unknown cards and retain the identities of cards generated by effects. */
export function botSimulation(view:BotView):Game {
  const hands:[number[],number[]]=[[],[]];hands[view.player]=[...view.hand];
  hands[opponent(view.player)]=Array(view.enemyHandCount).fill(1);
  const tag=view.rulesVersion?{rulesVersion:view.rulesVersion}:{};
  return {...tag,board:structuredClone(view.board),hands,decks:view.deckCounts.map(n=>n>0?[1]:[]) as Game['decks'],
    discard:structuredClone(view.discard),mulliganDone:[true,true],phase:'playing',turn:view.player,passes:view.passes,
    history:[],events:[],nextInstanceId:view.nextInstanceId,replay:{...tag,version:1,seed:0,decks:[[],[]],firstPlayer:view.player,commands:[]}};
}
export function simulateBotAction(game:Game,action:BotAction):Game {
  const trial=structuredClone(game);
  if(action.type==='pass')pass(trial,action.player);
  else play(trial,action.player,action.handIndex,action.row,action.col);
  return trial;
}
export function botActions(game:Game,onlyFirst=false):BotAction[] {
  const seen=new Set<string>();
  const moves=legalMoves(game,game.turn).filter(m=>{
    if(onlyFirst&&m.handIndex!==0)return false;
    const key=`${game.hands[game.turn][m.handIndex]}:${m.row}:${m.col}`;
    if(seen.has(key))return false;seen.add(key);return true;
  });
  return [{type:'pass',player:game.turn},...moves.map(m=>({type:'play' as const,player:game.turn,...m}))];
}
export function evaluateBotPosition(game:Game,player:Player):{score:number;reason:string} {
  const enemy=opponent(player),result=outcome(game),margin=result.scores[player]-result.scores[enemy];
  if(game.phase==='finished')return {score:Math.sign(margin)*1_000_000+margin,reason:`终局有效分差 ${margin}`};
  let territory=0;
  for(let row=0;row<3;row++)for(let col=0;col<5;col++){
    const t=game.board[row][col];if(t.owner===null)continue;
    const advance=t.owner===0?col:4-col;
    // A placed card still controls its tile. Extra pawn ranks only help on open tiles.
    territory+=(t.owner===player?1:-1)*(1+Math.max(1,t.pawns)*.4+advance*.25);
  }
  const power=result.rows.reduce((sum,r)=>sum+r[player]-r[enemy],0);
  const resources=game.hands[player].length-game.hands[enemy].length;
  return {score:margin*5+power*.8+territory*2+resources*.35,
    reason:`有效分差 ${margin}，行力量差 ${power}，领地/空格等级/纵深差 ${territory.toFixed(1)}`};
}
function shuffled<T>(rows:T[],random:()=>number):T[]{
  const copy=[...rows];for(let i=copy.length-1;i>0;i--){const j=Math.floor(random()*(i+1));[copy[i],copy[j]]=[copy[j],copy[i]];}return copy;
}
/** The same root cost and response hypotheses are used by Bot and replay study. */
export function assessBotRoot(game:Game,view:BotView,action:BotAction){
  const assessed=evaluateBotPosition(game,view.player);
  const cost=action.type==='play'?byId.get(view.hand[action.handIndex])!.power*.12:0;
  return {score:assessed.score-(game.phase==='finished'?0:cost),reason:assessed.reason};
}
export function botReplyHypotheses(game:Game,view:BotView,replySeed:number){
  const enemy=opponent(view.player),replies:{game:Game;action:BotAction}[]=[{game,action:{type:'pass',player:enemy}}];
  const count=game.hands[enemy].length;
  const added=game.events.filter(e=>e.type==='CardAddedToHand'&&e.player===enemy);
  const drew=added.some(e=>e.reason==='draw');
  const generated=added.flatMap(e=>e.reason==='generated'&&e.cardId!==undefined?[e.cardId]:[]);
  const pool=[...new Set([...(view.enemyHandCount>0||drew?RESPONSE_POOL:[]),...generated])];
  if(count>0)for(const id of pool){
    const hypothesis=structuredClone(game);hypothesis.hands[enemy]=[id,...Array(count-1).fill(1)];
    for(const action of botActions(hypothesis,true).slice(1))replies.push({game:hypothesis,action});
  }
  return [replies[0],...shuffled(replies.slice(1),seededRng(Math.floor(replySeed*0x100000000)))];
}
export function decideBot(view:BotView,options:BotOptions={}):BotDecision {
  const difficulty=options.difficulty??'normal',seed=options.seed??1,maxNodes=options.maxNodes??DEFAULT_BOT_NODES[difficulty];
  if(!['easy','normal','hard'].includes(difficulty))throw Error('Unknown Bot difficulty');
  if(!Number.isInteger(seed)||seed<0||seed>0xFFFFFFFF)throw Error('Bot seed must be uint32');
  if(!Number.isInteger(maxNodes)||maxNodes<1||maxNodes>512)throw Error('Bot maxNodes must be 1..512');
  const initial=botSimulation(view),random=seededRng(seed),[passAction,...placements]=botActions(initial);
  const closesWin=view.passes===1&&outcome(initial).winner===view.player;
  const stats={nodes:0,maxNodes,rejected:0,depth:0,budgetReached:false};
  const candidates:BotCandidate[]=[],roots:{game:Game;candidate:BotCandidate}[]=[];
  const simulate=(game:Game,action:BotAction)=>{
    if(stats.nodes>=maxNodes){stats.budgetReached=true;return null;}
    stats.nodes++;
    try{return simulateBotAction(game,action);}catch{stats.rejected++;return null;}
  };
  const passReason=(candidate:BotCandidate)=>{
    if(!placements.length)return '当前手牌无合法出牌，PASS';
    if(closesWin)return '连续 PASS 可以锁定胜局';
    if(candidates.some(c=>c.action.type==='play'))return `评估选择 PASS · ${candidate.reason}`;
    return stats.budgetReached?'预算内未找到可结算出牌，PASS':'候选出牌无法结算，PASS';
  };
  const finish=(candidate:BotCandidate):BotDecision=>({action:candidate.action,difficulty,seed,stats,reason:candidate.action.type==='pass'?passReason(candidate):candidate.reason,
    ...(options.explain?{candidates:candidates.map(c=>({...c,score:Math.round(c.score*1000)/1000}))}:{})});
  if(difficulty==='easy'){
    const ordered=closesWin?[passAction]:[...shuffled(placements,random),passAction];
    for(const action of ordered){
      const trial=simulate(initial,action);if(!trial){if(stats.budgetReached)break;continue;}
      stats.depth=1;const candidate={action,score:0,immediate:0,replies:0,reason:'固定种子随机合法行动（已通过共享引擎模拟）'};
      candidates.push(candidate);return finish(candidate);
    }
    return finish({action:{type:'pass',player:view.player},score:0,immediate:0,replies:0,reason:'预算内未找到可结算落子，PASS'});
  }
  const rootLimit=difficulty==='hard'?Math.min(32,Math.max(1,Math.floor(maxNodes/3))):maxNodes;
  const moves=shuffled(placements,random);
  const ordered=rootLimit===1&&!closesWin?[...moves,passAction]:[passAction,...moves];
  for(const action of ordered.slice(0,rootLimit)){
    const trial=simulate(initial,action);if(!trial)continue;
    const assessed=assessBotRoot(trial,view,action),score=assessed.score;
    const candidate={action,score,immediate:score,replies:0,reason:assessed.reason};
    candidates.push(candidate);roots.push({game:trial,candidate});stats.depth=1;
  }
  if(ordered.length>rootLimit)stats.budgetReached=true; // Includes deliberate beam pruning.
  roots.sort((a,b)=>b.candidate.score-a.candidate.score);
  if(difficulty==='hard'){
    const beam=roots.slice(0,6),quota=Math.floor((maxNodes-stats.nodes)/Math.max(1,beam.length));
    const explored:BotCandidate[]=[];
    for(const root of beam){
      const candidate=root.candidate;
      if(root.game.phase==='finished'){explored.push(candidate);continue;}
      if(quota<1)break;
      const queue=botReplyHypotheses(root.game,view,random());
      let worst=Infinity,used=0;
      for(const reply of queue){
        if(used>=quota){stats.budgetReached=true;break;}used++;
        const trial=simulate(reply.game,reply.action);if(!trial)continue;
        worst=Math.min(worst,evaluateBotPosition(trial,view.player).score);candidate.replies++;stats.depth=2;
      }
      if(candidate.replies){candidate.score=worst;candidate.reason+=`；公开假设回应最差评分 ${worst.toFixed(1)}（${candidate.replies} 项）`;explored.push(candidate);}
    }
    if(explored.length){explored.sort((a,b)=>b.score-a.score);return finish(explored[0]);}
  }
  return finish(roots[0]?.candidate??{action:{type:'pass',player:view.player},score:0,immediate:0,replies:0,reason:'没有可结算落子，PASS'});
}
export function recommendBot(game:Game,player:Player=game.turn,options:BotOptions={}):BotDecision {return decideBot(observeGame(game,player),options);}
